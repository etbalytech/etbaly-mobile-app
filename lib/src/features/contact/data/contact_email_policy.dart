bool isValidContactEmail(String value) =>
    RegExp(r'^[^\s@]+@[^\s@]+\.[^\s@]+$').hasMatch(value.trim());

bool isAllowedEmailDomain(String email) {
  final lower = email.toLowerCase().trim();
  final at = lower.lastIndexOf('@');
  if (at < 1) return false;
  final domain = lower.substring(at + 1);

  if (_blockedEmailDomains.contains(domain)) return false;
  if (_allowedEmailDomains.contains(domain)) return true;

  final parts = domain.split('.');
  if (parts.length < 2) return false;
  final sld = parts[parts.length - 2];
  final tld = parts.last;
  if (sld.length < 2 || tld.length < 2) return false;

  if (_suspiciousTlds.contains(tld)) return false;
  if (_disposableKeywords.any(sld.contains)) return false;

  return true;
}
